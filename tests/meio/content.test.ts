describe('карта MEIO: привязка к алгоритмам платформы', () => {
  it('каждый блок несёт ровно те имена алгоритмов, что заявил владелец', () => {
    for (const [label, expected] of Object.entries(ALGORITHM_BY_STEP)) {
      expect(step(label)?.algorithms, `шаг «${label}»`).toEqual(expected);
    }
  });

  it('шаги без алгоритма — ручные, и их ровно пять', () => {
    // Это не пробел привязки, а факт: у шага нет алгоритма в платформе, потому
    // что он выполняется человеком (сбор данных, задание параметров, экспертная
    // правка CV, разбор предупреждений) либо сводит результаты уже посчитанного.
    const manual = steps.filter((item) => item.algorithms === undefined);
    expect(labels(manual)).toEqual(
      [
        'Подготовка данных',
        'Настройка параметров расчёта',
        'Корректировка CV спроса',
        'Корректировка CV длительности поставок',
        'Корректировка CV длительности производства',
        'Анализ предупреждений расчёта',
        'Отчёт по OTIF',
        'Оценка эффектов',
      ].sort(),
    );
    expect(manual).toHaveLength(8);
  });

  it('один алгоритм — один блок: повторов между блоками нет', () => {
    // Ради этого свойства карта и перестраивалась. Повтор означал бы, что один
    // и тот же расчёт нарисован в двух местах процесса.
    const all = steps.flatMap((item) => item.algorithms ?? []);
    expect(new Set(all).size).toBe(all.length);
    expect(all).toHaveLength(18);
  });

  it('«Усреднитель» стоит на основном расчёте — единственный блок с двумя именами', () => {
    // Уточнение владельца от 07.09.2026: усреднение не отдельный шаг подготовки,
    // а часть основного расчёта. Поэтому у мультиэшелонной оптимизации два имени,
    // а у всех остальных блоков — по одному.
    const multi = steps.filter((item) => (item.algorithms ?? []).length > 1);
    expect(labels(multi)).toEqual(['Мультиэшелонная оптимизация']);
    expect(step('Мультиэшелонная оптимизация')?.algorithms).toContain('MEIO Усреднитель');
  });

  it('весь реестр модуля разобран по блокам — контур замкнут', () => {
    // Решение владельца 08.09.2026: «давай добавим этот шаг». «MEIO Передача
    // нормативов по запасам в SNP» оставалась единственным алгоритмом без блока,
    // потому что карта заканчивалась отчётом — расчётом, у результата которого
    // нет получателя (находка MEIO-1 панели Fusion). Шаг добавлен, и теперь
    // привязаны все 18 имён реестра.
    const all = steps.flatMap((item) => item.algorithms ?? []);
    expect(all).toContain('MEIO Передача нормативов по запасам в SNP');
    expect(step('Передача нормативов по запасам в SNP')?.outputs).toEqual([
      'Опубликованные нормативы запасов в SNP',
    ]);
    // Публикация идёт ПОСЛЕ оценки эффектов: публикуются согласованные значения,
    // а не всё посчитанное.
    const stage = map.stages[4];
    const idOf = (label: string): string | undefined =>
      stage?.nodes.find((node) => node.label === label)?.id;
    expect(
      (stage?.edges ?? []).some(
        (e) =>
          e.source === idOf('Оценка эффектов') &&
          e.target === idOf('Передача нормативов по запасам в SNP'),
      ),
    ).toBe(true);
    // Нормативы уходят наружу, в SNP: у этапа появился внешний выход.
    expect(stage?.outputs.map((io) => io.system)).toEqual(['INPLAN']);
  });

  it('у КАЖДОГО расчёта CV своя корректировка', () => {
    // Правка владельца 08.09.2026: «у каждого должна быть корректировка cv».
    // Общая корректировка на три расчёта скрывала бы, чья именно правка внесена:
    // спрос правит планер, длительность поставки — закупки, длительность
    // производства — производственный планер. Проверяется рёбрами, а не
    // подписями: подпись можно поправить, не тронув поток.
    const stage = map.stages[1];
    const idOf = (label: string): string | undefined =>
      stage?.nodes.find((node) => node.label === label)?.id;
    const edge = (from: string, to: string): boolean =>
      (stage?.edges ?? []).some((e) => e.source === idOf(from) && e.target === idOf(to));

    const pairs: [string, string, string][] = [
      ['Расчёт волатильности спроса', 'Корректировка CV спроса', 'Скорректированный CV спроса'],
      [
        'Расчёт CV длительности поставок',
        'Корректировка CV длительности поставок',
        'Скорректированный CV длительности поставок',
      ],
      [
        'Расчёт CV длительности производства',
        'Корректировка CV длительности производства',
        'Скорректированный CV длительности производства',
      ],
    ];
    for (const [calc, fix, result] of pairs) {
      expect(edge(calc, fix), `${calc} → ${fix}`).toBe(true);
      expect(step(fix)?.outputs, fix).toEqual([result]);
      // Корректировка ручная: у неё нет алгоритма в платформе.
      expect(step(fix)?.algorithms, fix).toBeUndefined();
    }

    // Все три скорректированных CV уходят в основной расчёт.
    for (const [, , result] of pairs) {
      expect(step('Мультиэшелонная оптимизация')?.inputs, result).toContain(result);
    }
  });

  it('владельцы корректировок разные — в этом и был смысл разделения', () => {
    expect(step('Корректировка CV спроса')?.owner).toBe('Планер запасов');
    expect(step('Корректировка CV длительности поставок')?.owner).toBe(
      'Закупки совместно с планером запасов',
    );
    expect(step('Корректировка CV длительности производства')?.owner).toBe(
      'Производственный планер совместно с планером запасов',
    );
  });

  it('сегментация — отдельный этап со своими входами', () => {
    // Правка владельца 08.09.2026: «сегментация — это следующий процесс и у него
    // свои входы должны быть». Раньше она была группой внутри подготовки к
    // расчёту и делила входы с настройкой параметров.
    const segmentation = map.stages[2];
    expect(segmentation?.title).toBe('Сегментация');
    expect(segmentation?.nodes.filter((node) => node.type !== 'data')).toHaveLength(2);
    // Входные карточки у этапа свои, а не унаследованные от подготовки.
    const inputLabels = (segmentation?.nodes ?? [])
      .filter((node) => node.type === 'data' && node.direction === 'in')
      .map((node) => node.label);
    for (const label of [
      'История потребления за период',
      'Вклад в оборот и объём',
      'Частота обращения позиции',
      'Стадия жизненного цикла товара',
      'Скорректированный CV спроса',
    ]) {
      expect(inputLabels, label).toContain(label);
    }
    expect(inputLabels).not.toContain('Плановые лидтаймы и отклонения');
  });
});

describe('карта MEIO: адресные входы', () => {
  it('у каждого расчёта CV свои карточки входов, а не общая колонка этапа', () => {
    // Правка владельца 08.09.2026: «для CV длительности производства и CV
    // длительности поставок нужно указать свои входы». Раньше ВСЕ карточки
    // входов этапа сходились к первому шагу — на этапе с одним шагом это верно,
    // на этапе из семи это неправда, которую видно глазами.
    const stage = map.stages[1];
    const labelOf = new Map(stage?.nodes.map((node) => [node.id, node.label]));
    const consumerOf = (card: string): string | undefined => {
      const id = stage?.nodes.find((node) => node.label === card)?.id;
      return labelOf.get(stage?.edges.find((edge) => edge.source === id)?.target ?? '');
    };

    const expected: [string, string][] = [
      ['История отгрузок за период', 'Расчёт волатильности спроса'],
      ['Собственная история прогноза и факта', 'Расчёт волатильности спроса'],
      ['Плановые и фактические длительности поставок', 'Расчёт CV длительности поставок'],
      ['Отклонения по дугам сети', 'Расчёт CV длительности поставок'],
      ['Плановые и фактические длительности производства', 'Расчёт CV длительности производства'],
      ['Отклонения по производственным заказам', 'Расчёт CV длительности производства'],
    ];
    for (const [card, consumer] of expected) {
      expect(consumerOf(card), card).toBe(consumer);
    }

    // Умолчание сохранено: подпись, для которой потребитель не назван, идёт к
    // первому шагу потока.
    expect(consumerOf('Затраты на хранение')).toBe('Настройка параметров расчёта');
  });

  it('отчёт по OTIF — замер факта со своими входами', () => {
    // Правка владельца 08.09.2026: «нужно показать входы для отчетов по OTIF».
    // Остальные отчёты этапа читают то, что модуль посчитал; этот — то, что
    // получилось у бизнеса на нормативах прошлого цикла, и без собственных
    // входов он неотличим от отчёта о рекомендациях.
    const otif = step('Отчёт по OTIF');
    expect(otif).toBeDefined();
    expect(otif?.outputs).toEqual([
      'Фактический OTIF по клиентам и каналам',
      'Отклонения от целевого OTIF',
    ]);

    const stage = map.stages[4];
    const labelOf = new Map(stage?.nodes.map((node) => [node.id, node.label]));
    const consumerOf = (card: string): string | undefined => {
      const id = stage?.nodes.find((node) => node.label === card)?.id;
      return labelOf.get(stage?.edges.find((edge) => edge.source === id)?.target ?? '');
    };
    for (const card of [
      'Заказы клиентов: даты и количества',
      'Фактические отгрузки: даты и количества',
      'Целевой OTIF по каналам и сетям',
      'Опубликованные нормативы прошлого цикла',
    ]) {
      expect(consumerOf(card), card).toBe('Отчёт по OTIF');
    }
  });

  it('у отчёта по OTIF алгоритма НЕТ, и это сказано прямо', () => {
    // Замер OTIF выходит за периметр MEIO: в реестре модуля такого алгоритма
    // нет. Карта не должна обещать функциональности, которой в модуле нет.
    expect(step('Отчёт по OTIF')?.algorithms).toBeUndefined();
    expect(step('Отчёт по OTIF')?.description).toContain('в реестре модуля нет');
  });
});

